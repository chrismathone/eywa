/**
 * 교재 요청 1건의 **"내 것" 판정**(순수 함수) — 강사가 수정·삭제·학부모 발송해도 되는가.
 *
 * 🔴 왜 필요한가(2026-07-29 적대 감사): 게이트가 **담당 학생 여부뿐**이었다
 * (`loadEditableRequest`·`loadScopedOrders`). 수학과 영어를 같이 듣는 학생은 두 강사 모두의 담당이라,
 * **영어 강사 화면에 수학 강사가 낸 교재 요청이 그대로 뜨고 수정·삭제·학부모 발송 버튼까지 살아 있었다.**
 * 화면엔 작성 강사명도 없어서 남의 것인 줄 알 방법이 없었다. 원장 결정 = **"본인이 만든 요청만"**.
 *
 * ⚠️ **판정 키가 `teacher_name`인 이유**: `textbook_orders`엔 작성자 uuid 컬럼이 없다. 있는 건 폼의
 * '담임 선생님'(자유 표시명, **대리 작성 가능** — `requestTextbook`가 미입력 시 요청자 본인으로 채운다).
 * 그래서 이 값은 "이 요청이 누구 것인가"의 최선 근사다. 대리 작성이면 이름을 적어 넣은 **그 강사**의 것이
 * 되는데, 그게 의도한 의미이기도 하다("담임 선생님 앞으로 낸 요청").
 *
 * ⚠️ **정확 일치 + fail-closed**: 표기 흔들림(`셀린T`/`셀린t`/`김정은T`)을 느슨하게 맞추지 않는다 —
 * 느슨하게 하면 남의 요청을 내 것으로 오판해 **바로 그 버그가 되돌아온다**. 매칭 실패 시 읽기 전용이 되고,
 * 사무실(master/accountant)은 이 게이트를 아예 안 탄다(`effectiveTeacherId()`가 null) → 처리 경로는 안 막힌다.
 * 실측 2026-07-29: 수정 가능한(사무실 미처리) 4건 전부 현직 강사 표시명과 정확 일치(100%).
 *
 * 🔴 **알려진 부작용(2026-07-29 실측, 원장 판단 대기)**: `김은정` 선생님의 과거 요청 51건이 본인 표시명이
 * 아니라 **별칭**으로 저장돼 있다 — `셀린T` 45건(users.english_name이 `Celine`), `김정은` 6건(이름 전치 오타).
 * 이 값들은 코드로 `김은정`과 이을 방법이 없어(한글 음차·전치는 규칙화 불가) 그 51건이 **본인에게도 읽기 전용**이
 * 된다. 느슨한 매칭으로 풀면 남의 요청을 내 것으로 오판해 원래 버그가 되돌아오므로 **코드로 추측하지 않는다.**
 * 정답 = **데이터 정규화**(`teacher_name` 셀린T/김정은/김정은T → 김은정) 한 번. 그러면 이 함수는 그대로 맞는다.
 * ⚠️ 비교 대상: `박민엽`·`남정화`가 0건이 되는 건 **정당하다** — 그 학생들 요청은 실제로 이수진·이유정 것이다.
 *
 * ⚠️ **표시명을 바꾸면 과거 요청이 읽기 전용이 된다**(같은 이유 — `teacher_name`은 그 시점 이름의 스냅샷).
 * 직원관리에서 강사 표시명을 바꿀 땐 그 강사의 `textbook_orders.teacher_name`도 함께 옮길 것.
 *
 * 📌 `textbook_orders.created_by` 컬럼이 생기면 그걸 1순위로 보고 이 이름 매칭은 레거시 폴백으로 내릴 것 —
 *    위 별칭·개명 문제가 한 번에 사라진다(이 함수는 폴백으로 남는다).
 */
export function ownsTextbookRequest(
  teacherName: string | null | undefined,
  viewerDisplayName: string | null | undefined,
): boolean {
  const owner = teacherName?.trim();
  const me = viewerDisplayName?.trim();
  return !!owner && !!me && owner === me;
}
