-- 0194a — 수강료 단가표: attendance 이관 산물을 **완전히 삭제**한다.
--
-- 원장 2026-08-07: *"여전히 일부 단가에 attendance 단가표 이관이란 글자가 떡 하니 남아있는데?
-- 중지된것들도 전부 삭제해야지"*.
-- 0193a에서 비활성화만 했더니 단가표 목록(상태=전체)에는 그대로 남아 비고의 이관 문구까지 보였다.
--
-- 실측(적용 직전): 중지 항목 54건 = **전부** 이 이관 산물이다(다른 사유로 중지된 항목 0건).
--
-- 🔴 되돌릴 수 없다. 그래도 안전한 이유:
--   · 이 표를 참조하는 **FK가 없다**(실측 0개).
--   · 견적(`tuition_quotes.courses`)은 단가표를 참조하지 않고 **이름·금액을 복사해** 저장한다
--     → 이미 저장된 견적·인쇄물은 이 삭제에 영향받지 않는다.
--   · 활성 목록(50건)은 손대지 않는다 — 조건이 `is_active = false`다.
--
-- ⚠️ 삭제되는 것 중 **과학 4건은 정식 대응이 없다**(단가표 분류에 '과학'이 없어 '기타'로 들어왔다).
--    되살릴 일이 생기면 아래 값으로 다시 등록해야 한다 — 지워지면 이 주석이 유일한 기록이다:
--      고등 통합과학 30,000 · 과학특강1 20,833 · 과학특강2 21,250 · 중등 과학정규 25,000
--    (전부 회당 단가로 이관돼 있던 값. 분류를 먼저 만든 뒤 등록할 것.)

delete from public.tuition_catalog
 where note = 'attendance 단가표 이관(2026-07-13)'
   and is_active = false;

