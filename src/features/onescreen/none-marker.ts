/**
 * "과제가 **없었다**"를 정식 값으로 다루는 규약 — 원장 지시(2026-07-23): *"없음 추가 (추세에서 제외)"*.
 *
 * 왜 필요한가: 신규생·특강 첫날처럼 **지난 과제가 존재할 수 없는** 날이 있는데 선택지가
 * 완료/일부 미흡/미제출뿐이라, 강사들이 자유입력 칸에 `-`·`X`·`없음`을 제각각 적어 왔다
 * (실측 67건). 그 값은 그대로 학부모에게 나가고("오늘 과제: -"), AI 멘트는 그걸 사실로 받아
 * "오늘 과제는 -입니다."로 마무리한다.
 *
 * 규약 두 줄:
 *  ① 표기는 **"없음" 하나로 통일**한다(지우지 않는다 — "오늘은 숙제가 없다"는 학부모에게 유용한 정보다).
 *  ② **추세에서는 제외**한다. 🔴 `없음`은 `미제출`이 아니다 — 과제가 없던 날을 0%로 세면
 *     성실한 학생이 미제출로 몰린다. 그래프도 마찬가지(`parseHomeworkPercent`가 숫자 없는 값을
 *     null로 떨궈 이미 제외되지만, 의도를 테스트로 못박는다).
 *
 * ⚠️ 이 정규화는 **저장 시점**(서버)과 **추세 조립 시점**(순수) 양쪽에 건다. 저장 시점만 걸면
 *    이미 쌓인 이관분 67건이 계속 추세를 오염시키고, 조립 시점만 걸면 학부모 카드에 `-`가 계속 나간다.
 */

/** 화면·학부모 카드에 나가는 표준 표기. */
export const NONE_LABEL = "없음";

/**
 * "없다"는 뜻으로 강사들이 실제로 적어온 값들(실측 + 흔한 변형). 소문자로 비교한다.
 * ⚠️ 새 변형을 발견하면 여기에 추가할 것 — 여기 없으면 그 표기가 그대로 학부모에게 나간다.
 * ⚠️ 반대로 너무 넓히지 말 것("0"·"미흡" 등 **뜻이 다른 값**을 삼키면 진짜 기록이 사라진다).
 */
const NONE_TOKENS = new Set([
  "-",
  "--",
  "–",
  "—",
  ".",
  "x",
  "✕",
  "×",
  "없음",
  "없슴",
  "없었음",
  "무",
  "n/a",
  "na",
]);

/**
 * 자유입력 값 → 표준화. 빈 값이면 `null`(항목 자체를 안 내보냄), "없다"는 뜻이면 `"없음"`,
 * 그 외는 앞뒤 공백만 턴 원본. 순수 함수(Vitest).
 */
export function normalizeNoneMarker(raw: string | null | undefined): string | null {
  const s = raw?.trim();
  if (!s) return null;
  return NONE_TOKENS.has(s.toLowerCase()) ? NONE_LABEL : s;
}

/** 이 값이 "없었다"는 뜻인가 — 추세·그래프 제외 판정용. 정규화 전 원본에도 그대로 쓸 수 있다. */
export function isNoneValue(raw: string | null | undefined): boolean {
  const s = raw?.trim();
  return !!s && NONE_TOKENS.has(s.toLowerCase());
}
