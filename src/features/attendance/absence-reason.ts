/**
 * 메모 한 줄 → 사유 분류.
 *
 * 판정 순서는 **학교 → 병결 → 사전 통보**다. `수학여행`이 `여행`에, `병원 진료`가 다른 낱말에 먼저
 * 걸리지 않게 하기 위한 순서이므로 뒤집지 말 것.
 */
export function classifyAbsenceReason(note: string | null | undefined): AbsenceReasonKind {
  if (!note) return "unknown";
  const n = normalize(note);
  if (!n) return "unknown";
  if (SCHOOL_WORDS.some((w) => n.includes(w))) return "school";
  if (SICK_WORDS.some((w) => n.includes(w))) return "sick";
  if (PLANNED_WORDS.some((w) => n.includes(w))) return "planned";
  return "unknown";
}

/**
 * 그 결석이 **긴급으로 다뤄야 하나** — 사유를 모르고 아직 아무도 손대지 않은 것만 긴급이다.
 * 🔑 사유가 확인된 줄을 목록에서 **빼지는 않는다**(숨기면 "그날 결석이 몇이었나"가 깨진다). 뒤로 내릴 뿐이다.
 */
export function isUrgentAbsence(reason: AbsenceReasonKind, settled: boolean): boolean {
  return !settled && reason === "unknown";
}
