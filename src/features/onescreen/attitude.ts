/**
 * 수업 태도 — 선택지 + 문장 조각의 **단일 소스**.
 *
 * 원장 지시(2026-08-03): *"태도도 변경 — 매우 좋음/좋음/보통/안좋음/매우 안좋음."*
 * 이전 선택지(`아주 좋음·좋음·보통·산만함·피곤함`)는 좋음 쪽만 눈금이 있고 나쁜 쪽은 **증상**(산만·피곤)이라
 * 정도를 표현할 수 없었다. 이제 5단 눈금 하나로 위아래가 대칭이다.
 *
 * ⚠️ **옛 값은 지우지 않는다** — 실데이터에 `최고`(5,016건, edutrix 계보)·`아주 좋음`(403)·`좋음`·`나쁨`,
 *    심지어 `최고 책없음` 같은 자유입력이 남아 있다. 선택지에 없는 저장값도 입력칸이 그대로 보여 주고
 *    ([FieldSelect](./components/field-select.tsx)), 문장은 아래 폴백(`${값}입니다`)으로 옛 동작을 지킨다.
 */

/** 수업 태도 선택지 — 좋은 쪽부터. ⚠️ 화면마다 다시 적지 말 것(관리자 작성 화면도 이걸 import). */
export const ATTITUDE = ["매우 좋음", "좋음", "보통", "안좋음", "매우 안좋음"] as const;

/**
 * 학부모 문장에 넣을 조각. `end`=문장 끝맺음 · `join`=뒤에 다른 사실이 이어질 때("~고,").
 * 🔴 값을 **해석·평가하지 않는다** — 강사가 고른 정도를 한국어로 옮기기만 한다(비난 표현 금지 규칙과 동일선).
 */
const CLAUSE: Record<string, { end: string; join: string }> = {
  "매우 좋음": { end: "매우 좋았습니다", join: "매우 좋았고" },
  좋음: { end: "좋았습니다", join: "좋았고" },
  보통: { end: "보통이었습니다", join: "보통이었고" },
  안좋음: { end: "좋지 않았습니다", join: "좋지 않았고" },
  "매우 안좋음": { end: "많이 좋지 않았습니다", join: "많이 좋지 않았고" },
};

/** "수업 태도는" 뒤에 붙는 조각. 선택지 밖(옛 값·자유입력)은 예전처럼 값을 그대로 잇는다. */
export function attitudeClause(raw: string, mode: "end" | "join" = "end"): string {
  const s = raw.trim();
  const hit = CLAUSE[s];
  if (hit) return hit[mode];
  return mode === "end" ? `${s}입니다` : `${s}이고`;
}
