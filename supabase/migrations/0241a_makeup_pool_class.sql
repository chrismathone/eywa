-- 0241a: **보이지 않는 '보강' 반** — 반 없는 보강 출결이 앉을 자리 (2026-09-02).
--
-- 원장 지시(연속): *"그냥 출석부에 '보강' 반을 임시로 만들어서 그 아래에 학생이 있으면 돼. 그날만
-- 출석한것처럼"* → *"어느 반에서 보강한건 모르지 · 반 보강이 아니니까"* → *"보고서 발송건에 대해서는
-- 자동 입력 되어야지 / 발송 날자에 대해서는 수정할수도 있어야하고"* → *"실제로 수업을 했는데 출석부에
-- 시수가 없으면 이상하지."* → *"어디에서도 확인할 수 없는 그냥 코드로만 존재하는 가짜반을 만들자."*
--
-- 🔑 왜 반이 필요한가: 출결의 **강사 귀속은 반에서 나온다**(담임·교시 담당). 입력자(`recorded_by`)는
--    귀속이 아니다 — 실측 영어 출결 1,146행 중 1,138행을 한 사람이 대신 찍었다. 그래서 `class_id`를
--    비우면 "실제로 수업했는데 시수가 없다"가 화면에서만 해결되고 정산 축에는 주인이 없다.
--    → **강사마다 보이지 않는 반 하나**를 두고 그 반에 보강 출결을 앉힌다. 그러면 시수·칸 수정·게이트·
--    출석부 묶음이 **전부 기존 기계 그대로** 돈다(새 저장 경로 0).
--
-- 🔴 **안 보이게 하는 장치는 둘이고 순서가 있다**:
--   ① `is_active = false`로 만든다 → 활성만 보는 **거의 모든 목록**(수업목록 기본·반 드롭다운·시간표·
--      원스크린 로스터·ECS/MCS 랜딩·통계)에서 **필터 한 줄 없이** 자동으로 빠진다.
--   ② 그래도 **비활성까지 보여주는 곳**(수업목록 상태 필터)이 하나 있어서, 거기서만 이 컬럼으로 뺀다.
--   ⚠️ 이름(`보강 · 홍길동`)으로 판정하지 않는다 — 이름을 바꾸면 배선이 에러 없이 조용히 끊긴다
--      (테스트 학생 '학원이' 건에서 겪은 함정).
--
-- ⚠️ **적용 전에도 앱은 안 죽는다**(추가형): 컬럼이 없으면 이 반이 안 만들어지고, 보강 출결은 종전처럼
--    출석부에 안 남을 뿐이다(데이터는 안 깨진다). [[#95]] expand/contract.
alter table classes add column if not exists is_makeup_pool boolean not null default false;

comment on column classes.is_makeup_pool is
  '보이지 않는 ''보강'' 반인가(0241a). 반 없는 보강 출결이 앉는 자리 — 강사당 1개, is_active=false로 두어 목록에서 자동 제외되고, 비활성까지 보여주는 화면만 이 값으로 한 번 더 뺀다. 사람이 고르는 반이 아니다.';

-- 강사당 하나만 — 두 개가 생기면 같은 보강이 두 묶음으로 갈라진다(그리고 어느 쪽에 쓸지 비결정).
-- ⚠️ 부분 유니크라 `on conflict` 추론이 안 된다([[#113]]) — 생성부는 **먼저 조회하고 없으면 insert**한다.
create unique index if not exists classes_makeup_pool_per_teacher_uq
  on classes (tenant_id, teacher_id)
  where is_makeup_pool;
