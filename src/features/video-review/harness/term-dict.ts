/** 긴 말부터 바꾼다('원조율'이 '원조'보다 먼저). 고친 곳은 `정비례(전사: 정비를)`로 원래 말을 함께 남긴다. */
export function applyTermDict(text: string, dict: readonly (readonly [string, string])[] = TERM_DICT): string {
  const ordered = [...dict].sort((a, b) => b[0].length - a[0].length);
  // 한 번 바꾼 자리를 짧은 항목이 다시 바꾸지 않게 자리표로 잠근다.
  const marks: string[] = [];
  let out = text;
  for (const [wrong, right] of ordered) {
    out = out.split(wrong).join(`\u0000${marks.push(`${right}(전사: ${wrong})`) - 1}\u0000`);
  }
  return out.replace(/\u0000(\d+)\u0000/g, (_, i: string) => marks[Number(i)]);
}
