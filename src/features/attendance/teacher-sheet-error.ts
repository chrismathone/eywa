/**
 * 강사 출석부(강사 전체 보기)를 **돈 계산에 쓸 수 없는 상태** — 프리랜서 명세서·강사 정산 면이 이 오류를 받으면
 * 수업료를 산정하지 않고 사유를 그대로 보인다(종전 티어 정산으로 조용히 떨어지지 않는다).
 *
 * 🔑 출석부 화면은 조회가 일부 실패해도 표를 살리려고 접지만(표시), 같은 조립을 **금액**으로 쓰는 자리에선
 *    접힌 재료가 곧 틀린 금액이다(담임 이력이 비면 남의 반이 들어오고, 이월이 비면 청구액 상한이 달라진다).
 *    그래서 돈 경로(`loadTeacherSheet`)는 접힌 흔적이 있으면 이 오류를 던진다.
 * ⚠️ `message`는 화면에 그대로 뜬다 — 한글 사유만 적는다(원문·코드 금지).
 * ⚠️ 서버 전용이 아니다 — 판정(`instanceof`)을 테스트·호출부가 함께 쓴다([[#61]]).
 */
export class TeacherSheetError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "TeacherSheetError";
  }
}
