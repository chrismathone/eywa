/**
 * 모든 AI 호출에 **예외 없이** 붙는 사실 원칙 — 원장 지시(2026-07-23):
 * "AI 프롬프트 거칠때 '팩트' '환각금지' '사실만 작성' '창작 금지' '추측 금지'도 항상 거쳐야 해."
 *
 * 🔴 **왜 호출부 프롬프트가 아니라 코드에 두는가**
 *  ① 프롬프트 본문은 원장이 화면에서 편집할 수 있다(`ai_prompt_overrides`). 본문에만 적어 두면
 *     편집 한 번에 가드가 통째로 사라진다 — 지울 수 없는 자리에 둬야 "항상"이 성립한다.
 *  ② 호출부가 늘어날 때마다 각자 적어 넣게 하면 언젠가 빠뜨린다. 실제로 이 프로젝트에서
 *     "이름 없는 시험 기록에 모델이 시험 이름을 지어낸" 환각이 프로덕션 발송분에서 나왔다(2026-07-23).
 *
 * 부착 지점 = **`generateJSON()` 단일 진입점**(AI 정책의 단일 관문). 대화형 비서는 generateJSON을
 * 거치지 않는 자체 루프라 시스템 프롬프트에 같은 상수를 직접 잇는다.
 *
 * ⚠️ 이 문구를 완화·삭제하지 말 것. 항목별 세부 규칙(예: "전망 금지", "점수 숫자 그대로")은
 *    호출부 프롬프트가 계속 담당한다 — 여기는 **최소 공통 바닥**이다.
 */
export const FACT_GUARD = [
  "[사실 원칙 — 예외 없이 적용]",
  "- 팩트만 쓴다. 주어진 자료에 실제로 있는 사실만 작성한다.",
  "- 환각 금지 · 창작 금지 · 추측 금지.",
  "- 자료에 없거나 확실하지 않은 것은 지어내지 말고 아예 언급하지 않는다.",
  "- 이름·명칭·분류·수치를 임의로 채워 넣지 않는다(비어 있으면 비어 있는 대로 둔다).",
].join("\n");

/**
 * 프롬프트 앞에 사실 원칙을 붙인다. **멱등** — 이미 붙어 있으면 다시 붙이지 않는다
 * (호출부가 직접 붙인 뒤 generateJSON을 타도 중복되지 않게).
 */
export function withFactGuard(prompt: string): string {
  if (prompt.includes(FACT_GUARD)) return prompt;
  return `${FACT_GUARD}\n\n${prompt}`;
}
