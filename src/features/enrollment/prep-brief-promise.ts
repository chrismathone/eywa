import { BRIEF_FACT_TOPICS } from "@/features/enrollment/brief-facts";

/**
 * 상담 준비 브리프 — 학부모에게 하는 말 속 **운영 약속** 판정과 **말투 관찰**(검수 2026-11-11 · Claude·Codex 합의 3회 · 적대 리뷰 6회).
 *
 * 학원이 실제로 하는 일(보고 주기·과제·오답 관리·보강·체험·할인)은 브리프 사실에 없다. 모델이 학부모 바람을 '해 드리겠습니다'로
 * 되돌리면 지킬 수 없는 약속이 된다(저장본 실패 37건 대부분).
 *
 * 🔴 원칙(6차 리뷰 뒤 확정 · Codex 2차 합의 "인용이 있다는 이유로 문장 전체를 면제하지 않는다 · 40자 제한"):
 *   **문장 전체로 보수적으로 막고, 예외는 실데이터에서 오탐이 난 꼴 하나만** — 순수한 넘김 절('그 외 할인 조건은 제가 지금
 *   설명드리겠습니다'). 학부모 바람 인용·절 나누기 예외를 열 때마다 '…적어 주셨는데, 그 부분은 꼭 알려 드리겠습니다' 같은 약속이
 *   새로 풀렸다(3~6차). 인용 문장이 함께 막히는 것은 감수한다 — 막히면 그 항목 하나만 빠진다(재생성 177건에서 0건).
 */

const INFORM = /(안내|말씀|여쭤|여쭙|확인|설명|상의)$/;
/** 서비스 주기 — 뒤 40자 안에 하겠다는 말이 오면 약속. */
const SERVICE_FREQ =
  "매주|매달|매월|주마다|달마다|격주|정기적으로|매 수업|수업마다|수업 (?:후|뒤|끝나고|마치고)|수업이 끝나면|끝날 때마다|일주일에 한 ?번|한 달에 한 ?번";
/** 아이 행동을 말할 때가 많은 빈도어('매번 같은 유형을 틀린다') — 전하는 말이 붙을 때만 약속. '주 N회'는 수업 횟수('주3회 기준')로도 쓴다. */
const BEHAVIOR_FREQ = "매일|매번|주\\s*\\d+\\s*회";
const PROMISE =
  "드리겠|드릴게|드립니다|보내 ?드|해 ?드리|\\s하겠습니다|(?:보고|공유|정리|관리|기록|전달|점검|체크|발송|검사|챙기)하겠습니다|챙기겠|할게요|않겠습니다|나갑니다|나가는|발송|공유합|보냅니다";
const DELIVER = "보내 ?드|알려 ?드|(?:말씀|안내) ?드리|문자|연락|공유|정리해 ?드|체크해 ?드|발송|나갑|보냅";
const serviceFreqRe = new RegExp(`(${SERVICE_FREQ})[^.!?]{0,40}(${PROMISE})`);
const behaviorFreqRe = new RegExp(`(${BEHAVIOR_FREQ})[^.!?]{0,40}(${DELIVER})`);
const opsRe = new RegExp(
  "(할인|보강|체험 ?수업|무료 ?수업)[^.!?]{0,30}" +
    "(해 ?드리|드리겠|드릴게|드립니다|가능(?:합니다|하니|하고|해요|해서|하며)|되니|됩니다|돼요|무료(?:입니다|예요|이고|이며|이니|라서)|무료(?:로)?(?=\\s*(?:,|$))|(?:적용|진행|제공)되(?:고|며|지만|니)|(?:적용|진행|제공|잡아|잡고|마련)[^.!?]{0,10}(?:하겠|해 ?드리|드리|할게|합니다|됩니다))",
);
/** 순수한 넘김 절 — 'X은/는/도 (제가·지금·이 자리에서·직접…) 설명/말씀/안내드리겠습니다'. 주제와 넘김 사이에 다른 서술이 없을 때만. */
const HANDOFF_ADV = "(?:제가|지금|이 자리에서|바로|직접|이어서|자세히)";
/** 학원 설정의 운영 안내 원문을 가리키는 말('안내 문구 그대로 읽어 드리겠습니다' · 2026-11-12 운영 안내 시험에서 할인 약속으로 잘못 막혔다). */
// 🔴 원문·안내 문구·화면의 안내를 **분명히** 가리킬 때만 — '그대로'·'보며'만 있는 꼴('매주 진도는 그대로 말씀드리겠습니다')은 아니다(재리뷰 높음).
const GUIDE =
  "(?:지금\\s*)?(?:화면(?:에 실린|의)\\s*)?(?:(?:학원\\s*)?(?:운영\\s*)?안내(?:\\s*(?:문구|내용))?|원문)(?:를|을)?\\s*(?:(?:원문\\s*)?그대로|보시면서|보며|함께 보며)";
const TAIL_END = "\\s*(?:해\\s*)?(?:드리겠습니다|드릴게요|드립니다|하겠습니다)[.!?]?$";
const HANDOFF_TAIL = new RegExp(`(?:${HANDOFF_ADV}\\s+)*(?:설명|말씀|안내)${TAIL_END}`);
/** 원문 가리키기 꼬리 — 학원 설정에 운영 안내가 있을 때만 넘김으로 본다(없는데 '안내 문구 그대로 읽어 드리겠습니다'는 화면에 없는 글이다 · 적대 리뷰). */
const GUIDE_TAIL = new RegExp(`(?:${HANDOFF_ADV}\\s+)*${GUIDE}\\s*(?:${HANDOFF_ADV}\\s+)*(?:읽어|설명|말씀|안내)${TAIL_END}`);
const pureHandoff = (c: string, tail: RegExp) => new RegExp(`^[^.!?]*?(?:은|는|도)\\s+${tail.source}`).test(c);

/** 하겠다는 동사 — '설명해 드리'의 '해'는 떼되 '확인해 드리겠습니다'는 확인을 대신 해 주겠다는 약속이라 '확인해'로 남긴다(7차 리뷰). */
const verbsOf = (t: string) =>
  [...t.matchAll(/([가-힣]+)\s*(?:해\s*)?(?:드리겠|드릴게|드립니다|드리고|드리는)/g)].map((m) => (/^확인해서?$/.test(m[1]!) ? "확인해" : m[1]!.replace(/해서?$/, "")));
/** 확인·여쭙는 말이 있고 하겠다는 일이 알려 드리는 것뿐 — '보강이 가능한지는 확인해 말씀드리겠습니다'. */
const informOnly = (t: string) => {
  const v = verbsOf(t);
  return /(확인|여쭙|여쭤|가능한지|알아보|상의)/.test(t) && v.length > 0 && v.every((w) => INFORM.test(w));
};
const asksAbout = (t: string) => /(방식|가능한지|있는지|어떻게|여부|어떤|맞는지|되는지|맞을지)/.test(t);

/** 한 문장이 운영 약속이면 그 까닭, 아니면 null. 결과·기간 약속은 `problemOf`가 따로 본다. */
/**
 * 원문 가리키기 넘김을 인정할 주제인가 — 문장이 말하는 운영 주제가 하나 이상이고 **전부** 학원 설정에 적힌 주제일 때만
 * (할인 한 칸만 적은 지점에서 '매주 진도는 원문 그대로…'가 풀리지 않게 · 재리뷰).
 */
function guideCovers(s: string, guideTopics: readonly string[]): boolean {
  if (guideTopics.length === 0) return false;
  const mentioned = BRIEF_FACT_TOPICS.filter((t) => new RegExp(t.words).test(s));
  return mentioned.length > 0 && mentioned.every((t) => guideTopics.includes(t.label));
}

export function operationalPromise(sentence: string, opts: { guideTopics?: readonly string[] } = {}): string | null {
  // 전달 동사에 바로 붙은 부정('보내 드리지는 않습니다' · '드리진 않지만')은 약속이 아니다 — 그 말만 지운다(Codex 2차 합의).
  // 이중부정('…드리지 못하는 일은·적이·경우는 없습니다')은 약속이라 그대로 둔다.
  const s = sentence.replace(/[가-힣]+\s*(?:해\s*)?드리(?:지|진)(?:는|도|만)?\s*(?:않|못)(?![가-힣]*\s*(?:일|적|경우)(?:은|이|는|가)?\s*없)[가-힣]*/g, " ");
  // 순수한 넘김 절은 꼬리만 떼고 주제말은 남긴다(주제말 속 전제는 아래 ⑥이 본다). 쉼표 단위로만 — 그 밖의 절은 그대로 둔다.
  const topics: string[] = [];
  // 문장에 서비스 주기('매주 진도는' · '매 수업이 끝나면,')나 조건('결석하시면,')이 있으면 넘김이 아니라 그때 하겠다는 약속이다 —
  // 그 조각만이 아니라 문장 전체로 본다(7·8차 리뷰 · '따로'도 나중 약속이라 넘김 부사에서 뺐다).
  const timed = new RegExp(`(${SERVICE_FREQ}|매일|매번)|(?:하|시|으|나)면[\\s,]`).test(s);
  const guide = guideCovers(s, opts.guideTopics ?? []);
  const t = s
    .split(/,\s*/)
    .map((c) => {
      // 원문 가리키기도 때 말이 있으면 넘김이 아니다 — '매주 숙제를 어떤 방식으로 챙겨 드리는지는 원문 그대로…'처럼 원문의 주기·조건을
      // 바꾼 전제가 풀렸다(재리뷰 3차 높음). '수업 후 안내가 어떻게 돌아가는지는 화면의 원문 그대로…'(실데이터)는 감수하고 막는다.
      const tail = timed ? null : guide && pureHandoff(c.trim(), GUIDE_TAIL) ? GUIDE_TAIL : pureHandoff(c.trim(), HANDOFF_TAIL) ? HANDOFF_TAIL : null;
      if (!tail) return c;
      const topic = c.replace(tail, " ");
      topics.push(topic);
      return topic;
    })
    .join(", ");
  const asking = informOnly(t) && asksAbout(t);

  // ① 할인·보강·체험 단정 — '확인해 말씀드리겠습니다'처럼 알려 드리는 말뿐이면 아니다.
  if (!informOnly(t) && opsRe.test(t)) return "운영 약속(할인·보강·체험)";
  // '매월 말일 납부로 안내드립니다'는 정책 안내 — 단 보고·리포트를 보내는 말이 섞이면 약속이다.
  if (/(납부|납부일|말일)/.test(s) && !/(보고|리포트|보내|기록|피드백|문자|알림)/.test(s)) return null;
  // 수업 일정 표기('매주 월·수·금 16:30 수업' · '매주 세 번 수업')는 빈도 약속이 아니다 — 바로 뒤가 수업·반일 때만 지운다(7차 리뷰).
  const st = t
    .replace(/매주\s*(?:[월화수목금토일]·)*[월화수목금토일]\s*\d{1,2}:\d{2}\s*(?=수업(?:이|은|을|입니다|이고|이며|으로|,|\.)|반(?:[을이은에]|으로|\s|[,.]|$))/g, " ")
    .replace(/매주\s*(?:\d+|한|두|세|네|다섯)\s*(?:번|회)\s*(?=수업(?:이|은|을|입니다|이고|이며|으로|,|\.)|반(?:[을이은에]|으로|\s|[,.]|$))/g, " ");
  // ② 서비스 주기 + 40자 안 하겠다는 말('매주 진도를 확인해 말씀드리겠습니다'도 약속) — 방식·가능 여부를 확인해 알려 드리는 말만 예외.
  if (serviceFreqRe.test(st) && !asking) return "운영 약속(보고·관리 주기)";
  // ③ 매일·매번·주 N회 + 전하는 말('매일 숙제 결과를 알려 드리겠습니다').
  if (behaviorFreqRe.test(st) && !asking) return "운영 약속(보고·관리 주기)";
  // ④ 리포트·성적표·진도표를 보내거나 드리는 말은 빈도와 상관없이 약속 — 받는 쪽('공유해 주시면')·방식을 묻는 말은 아니다.
  if (!asking && /(리포트|성적표|보고서|진도표|학습 보고)[^.!?]{0,20}(보내 ?드|드리겠|드릴게|드립니다|발송|나갑|나가|보냅|공유(?:드|합|하겠|해 ?드))/.test(t)) {
    return "운영 약속(보고·관리 주기)";
  }
  // ⑤ '월별'·'정기 보고'는 서비스 이름 — 같은 문장에 하겠다는 행동이 있으면 약속(넘김 꼬리는 이미 뗐다 · '정기 보고 방식은 제가 지금
  //    설명드리겠습니다'는 통과). 그 수단으로 전하겠다는 말('월별로 … 말씀드리겠습니다' · '리포트로 안내드리겠습니다')도.
  if (/(월별|정기 보고)/.test(t)) {
    const doing =
      verbsOf(t).some((w) => !INFORM.test(w)) ||
      /보내 ?드|(?:공유|전달|발송|정리|기록|관리|보고|남겨|챙겨)\s*(?:해서|해|서)?\s*(?:드리|하겠|할게)|\s(?:하겠습니다|할게요)/.test(t);
    const via = /월별로[^.!?]{0,30}(?:안내|말씀)\s*(?:드리|하겠)|(?:리포트|성적표|보고서)로\s*(?:안내|말씀)\s*(?:드리|하겠|드립)/.test(t);
    if (doing || (via && !asking)) return "운영 약속(보고·관리 주기)";
  }
  // ⑥ 넘김 절 주제말 속 전제 — '매주 리포트를 어떤 방식으로 받아 보실지는' · '형제 할인이 적용되는 조건은'. 묻는 꼴('적용되는지')은 아니다.
  for (const c of topics) {
    if (new RegExp(`(${SERVICE_FREQ})[^.!?,]{0,20}(리포트|성적표|진도표|학습 보고|보고서)`).test(c)) return "운영 약속(보고·관리 주기)";
    if (/(할인|보강|체험 ?수업|무료)[^.!?,]{0,20}((?:적용되|진행되|제공되)(?![가-힣]*지)|가능한(?!지)|무료로|받으실 수 있)/.test(c)) return "운영 약속(할인·보강·체험)";
  }
  return null;
}

/**
 * 학부모에게 하는 말 칸들의 말투 관찰 — **고치지 않고 기록만**(폴백 판정·수리율과 따로 · 2차 합의).
 * 프롬프트 예문을 모델이 베껴 같은 말이 칸마다 붙는 일이 두 번 있었다('상담에서 확인해 안내' 건당 5.2 → '제가 지금 설명드리겠습니다' 건당 2).
 * 미루기 = 상담 뒤로 미루는 말 4문장 이상(지금·이 자리에서 확인하는 말 · '오늘 상담에서'는 아니다) · 넘김 = 설명을 넘기는 말 3문장 이상.
 */
export function observeSpoken(fields: string[]): string[] {
  const sentences = fields.flatMap((t) => t.split(/(?<=[.!?])\s+/)).filter(Boolean);
  const deferrals = sentences.filter((x) =>
    /((?<!(?:오늘|이번) )상담에서 확인|(?<!(?:지금|이 자리에서)[^.!?]{0,6})확인(?:해|하여|한 뒤|한 후|해서|하고|되는 대로|되면| 후)[^.!?]{0,15}(?:안내|말씀)|알아보(?:고|아서|아)[^.!?]{0,15}(?:안내|말씀)|알아본 뒤|추후 안내|따로 연락|검토해서|살펴보고[^.!?]{0,15}(?:안내|말씀)|상담 (?:후|뒤)[^.!?]{0,10}안내|나중에[^.!?]{0,15}(?:안내|말씀|알려)|다음에 다시|결과가 나오면[^.!?]{0,15}(?:연락|안내)|다시 안내)/.test(x),
  ).length;
  // 넘김 — 하겠다는 꼴(겠·게)만: '설명드리면'·'설명드리기 전에'·'설명드리던'은 넘김이 아니다.
  const handoffs = sentences.filter(
    (x) =>
      /(제가|지금|이 자리에서|상담사가|직접)[^.!?]{0,20}(?:설명|말씀)\s*(?:해\s*)?(?:드리겠|드릴게|하겠)/.test(x) ||
      /(상담사가|직접)[^.!?]{0,10}설명(?:드립니다|합니다)/.test(x) ||
      /^[^.!?]{0,25}(?:은|는)\s*(?:설명|말씀)\s*(?:해\s*)?드리겠습니다/.test(x) ||
      /그대로\s*(?:이어서\s*)?(?:읽어|설명|말씀|안내)\s*(?:해\s*)?드리겠/.test(x),
  ).length;
  const out: string[] = [];
  if (deferrals >= 4) out.push(`미루기 과다(${deferrals}문장)`);
  if (handoffs >= 3) out.push(`넘김 되풀이(${handoffs}문장)`);
  return out;
}
