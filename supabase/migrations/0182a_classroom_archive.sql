-- 0182a — 강의실 "숨김"(보관) — 삭제해도 배정이 미지정으로 바뀌지 않게 (2026-08-05).
--
-- 배경(원장 2026-08-05): *"강의실 삭제하더라도 미지정으로 바뀌지않고 그대로 남겨져있어야해."*
-- 지금은 `classes.classroom_id`·`class_schedules.classroom_id` FK가 **on delete set null**이라
-- 강의실 행을 지우면 그 방을 쓰던 반·시간표 슬롯이 전부 **미지정**이 된다(되돌릴 수 없다).
-- FK를 restrict로 바꾸면 이번엔 "쓰는 반이 있으면 아예 못 지움"이 되어 원장이 원한 것과 다르다.
--
-- → 해법은 **삭제가 아니라 보관(archive)**이다. 행은 남기고 `archived_at`만 찍는다:
--    · 목록·드롭다운 **선택지에서 사라진다**(새로 배정할 수 없다)
--    · 이미 배정된 반·슬롯은 **그 방을 그대로 가리킨다** — 시간표·교실뷰에 이름이 계속 나온다
--    · 되돌리기 = `archived_at = null`(복원)
--
-- ⚠️ **이름 유니크는 그대로 둔다**(`classrooms_tenant_name_idx (tenant_id, name)`).
--    보관된 방의 이름을 새 방에 다시 쓰면 시간표에 같은 이름이 둘이 되어 사람이 구분할 수 없다.
--    같은 이름을 다시 쓰려면 **복원**해서 쓴다(앱이 "보관된 같은 이름이 있습니다 — 복원하시겠어요?"로 안내).
--
-- ⚠️ 하드 삭제 경로는 **남겨 둔다** — 정말 잘못 만든 방(참조 0건)은 지울 수 있어야 한다.
--    참조가 있는 방은 앱이 삭제 대신 보관만 허용한다(미지정 전환을 원장이 명시적으로 금지했다).
--
-- 이 마이그레이션은 컬럼 추가뿐이라 **옛 앱에서도 안전**하다(읽지 않는 컬럼). 그래도 순서는
-- SQL 먼저 → 앱 배포다(새 앱이 이 컬럼을 select 한다, gotcha #95).

alter table classrooms add column if not exists archived_at timestamptz;

comment on column classrooms.archived_at is
  '보관(숨김) 시각. NULL=사용 중. 값이 있으면 새 배정 선택지에서 빠지지만, 이미 배정된 반·슬롯은 그대로 이 방을 가리킨다(0182a).';
