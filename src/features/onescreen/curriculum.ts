export const CURRICULUM_GRADES = Object.keys(MATH_CURRICULUM);

/** 학년별 커리큘럼(대단원/단원 목록). 없으면 빈 배열. */
export function curriculumForGrade(grade: string): CurriculumUnit[] {
  return MATH_CURRICULUM[grade] ?? [];
}

/**
 * 학생 학년 → 진도 피커 기본 진도학년(유효 커리큘럼 키). 초·중은 그대로("초3"/"중1").
 * 고등(고1~고3)은 과목 선택제라 학년명이 커리큘럼 키가 아니므로(키=공통수학1·대수·미적분2 …)
 * **시작 기본 과목**으로 보정한다 — 강사가 피커 드롭다운에서 실제 과목으로 바꾸면 세션에 저장된다.
 * 유효 키가 아니면 원값 유지(미정/성인 등은 빈 피커 = 현행 동작 동일).
 */
const HS_DEFAULT_SUBJECT: Record<string, string> = { 고1: "공통수학1", 고2: "대수", 고3: "미적분2" };
export function resolveStudyGrade(grade: string | null | undefined): string {
  const g = (grade ?? "").trim();
  if (CURRICULUM_GRADES.includes(g)) return g;
  const m = /^고\s*([123])/.exec(g);
  if (m) return HS_DEFAULT_SUBJECT[`고${m[1]}`] ?? "공통수학1";
  return g;
}

// ───────────────────────────── 학기 스코프 ─────────────────────────────
//   진도 피커: 학년 → 학기 → 차시 순으로 좁혀 드롭다운을 작게 만든다.

export type Semester = 1 | 2;

/**
 * 중등 1학기 마지막 단원(= 함수 단원). 이 단원까지 1학기, 그 다음부터 2학기.
 * 사용자 지정 경계: 중1=좌표평면과 그래프 / 중2=일차함수 / 중3=이차함수.
 * (초등은 단원 코드 prefix 1-/2-로 학기가 이미 구분됨.)
 */
const MIDDLE_SEM1_LAST_UNIT: Record<string, string> = {
  중1: "4. 그래프와 비례",
  중2: "4. 함수",
  중3: "4. 이차함수",
};

/** 단원이 속한 학기(1|2). 초등=코드 prefix, 중등=함수 단원 경계. */
export function unitSemester(grade: string, unit: string, index: number): Semester {
  if (unit.startsWith("1-")) return 1; // 초등 1학기
  if (unit.startsWith("2-")) return 2; // 초등 2학기
  const lastSem1 = MIDDLE_SEM1_LAST_UNIT[grade];
  if (!lastSem1) return 1;
  const boundary = (MATH_CURRICULUM[grade] ?? []).findIndex((u) => u.unit === lastSem1);
  return boundary >= 0 && index > boundary ? 2 : 1;
}

/** 그 학년에 존재하는 학기 목록(보통 [1, 2]). */
export function semestersForGrade(grade: string): Semester[] {
  const set = new Set<Semester>();
  curriculumForGrade(grade).forEach((u, i) => set.add(unitSemester(grade, u.unit, i)));
  return [...set].sort((a, b) => a - b);
}

/** 학년 + 학기로 스코프된 단원 목록(차시 드롭다운용). */
export function curriculumForGradeSemester(grade: string, semester: Semester): CurriculumUnit[] {
  return curriculumForGrade(grade).filter((u, i) => unitSemester(grade, u.unit, i) === semester);
}

/** 차시 문자열이 속한 학기. 못 찾으면 1학기로 간주(자동 입력 fallback). */
export function semesterOfLesson(grade: string, lesson: string): Semester {
  const units = curriculumForGrade(grade);
  for (let i = 0; i < units.length; i++) {
    const u = units[i];
    if (u && u.lessons.includes(lesson)) return unitSemester(grade, u.unit, i);
  }
  return 1;
}

// ───────────────────────── 다중 차시(진도) ─────────────────────────
//   한 수업에서 여러 차시를 나갈 수 있어(edutrix 패리티) `today`는 여러 차시를 **개행**으로 이어 붙인 문자열이다.
//   개행을 구분자로 쓰는 이유: 실제 차시 문자열에 "·"·"/"·","가 이미 들어 있어(예: 초5 "1-1-1 … 뺄셈 / 곱셈 …",
//   초6 "1-3-5 (자연수)÷(자연수), 어림셈 …") 그 문자로 나누면 단일 차시조차 오분할된다. 개행은 어떤 차시에도 없고,
//   progress-position.ts의 positionOf가 normalizeLegacy로 "마지막 줄=그날 최종 진도"를 채택하며,
//   parent-report-card 등 표시부가 whitespace-pre-line로 이미 개행을 인지한다.
export const PROGRESS_DELIM = "\n";

/** `today`(합본) → 차시 배열(공백/빈 항목 제거). 단일·다중·빈값 모두 안전. */
export function splitLessons(today: string | null | undefined): string[] {
  if (!today) return [];
  return today.split(PROGRESS_DELIM).map((s) => s.trim()).filter(Boolean);
}

/** 차시 배열 → `today` 합본 문자열(개행 조인). 순서 보존, 중복 제거. */
export function joinLessons(lessons: string[]): string {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const l of lessons) {
    const t = l.trim();
    if (t && !seen.has(t)) {
      seen.add(t);
      out.push(t);
    }
  }
  return out.join(PROGRESS_DELIM);
}

/** 첫 차시 — 학기 자동도출용(semesterOfLesson 인자). 없으면 "". */
export function firstLesson(today: string | null | undefined): string {
  return splitLessons(today)[0] ?? "";
}

/** 마지막 차시 — 그날 최종 진도(진도 위치 추적 대표). 없으면 "". */
export function lastLesson(today: string | null | undefined): string {
  const arr = splitLessons(today);
  return arr[arr.length - 1] ?? "";
}

/** 표시용 — 다중 차시를 ", "로 이어 한 줄로(개행 저장값을 좁은 곳에서 읽기 좋게). */
export function displayLessons(today: string | null | undefined): string {
  return splitLessons(today).join(", ");
}

/** 학년 커리큘럼을 단원 순서대로 flatten한 차시 배열(추천 진도·다중선택 원본). */
export function flatLessons(grade: string): string[] {
  return curriculumForGrade(grade).flatMap((u) => u.lessons);
}

/** afterLesson 다음 n개 차시(학년 내, 단원 경계 넘음). 못 찾으면 처음부터. edutrix "추천 진도" 칩용. */
export function nextLessons(grade: string, afterLesson: string, n = 3): string[] {
  const flat = flatLessons(grade);
  if (flat.length === 0) return [];
  const idx = afterLesson ? flat.indexOf(afterLesson) : -1;
  const start = idx >= 0 ? idx + 1 : 0;
  return flat.slice(start, start + n);
}
