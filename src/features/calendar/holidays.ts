/** 그 날의 공휴일명(정식 — "대체공휴일(광복절)" 포함). 공휴일이 아니거나 내장 범위 밖이면 null. */
export function holidayFor(ymd: string): string | null {
  return HOLIDAYS[ymd] ?? null;
}

export function isHoliday(ymd: string): boolean {
  return ymd in HOLIDAYS;
}

/** 칸에 찍는 짧은 이름 — "대체공휴일(광복절)" → "대체공휴일"(좁은 칸에서 괄호가 잘려 반토막 나느니 짧게). */
export function holidayShortName(ymd: string): string | null {
  const name = HOLIDAYS[ymd];
  if (!name) return null;
  return name.startsWith("대체공휴일") ? "대체공휴일" : name;
}
