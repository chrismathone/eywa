import { describe, expect, it } from "vitest";
import { hasMentLeak, stripMentLeaks, unescapeLiteral } from "./ment-leak";

describe("학부모 글의 AI 혼잣말·찌꺼기 거르기", () => {
  it("🔴 2026-11-12 실례 — 지시를 되받은 문장은 통째로 빼고, 글자 그대로의 줄바꿈 기호는 줄바꿈으로", () => {
    const real =
      "공배수와 최소공배수는 대체로 따라왔지만 아직 조금 어려워했습니다. 우리 재윤이가 공약수와 최대공약수, 공배수와 최소공배수를 차례로 익혔고, 공배수와 최소공배수 부분에서 조금 더 시간이 필요해 보였다는 말은 쓰지 않겠습니다.\n";
    expect(stripMentLeaks(real).text).toBe("공배수와 최소공배수는 대체로 따라왔지만 아직 조금 어려워했습니다.");
    expect(unescapeLiteral("첫 줄\n둘째 줄")).toBe("첫 줄\n둘째 줄");
  });
  it("작성 과정·규칙·응답 머리말·형식 찌꺼기", () => {
    for (const s of [
      "금지 표현이니 제외하고 다시 쓰겠습니다.",
      "지침에 따라 점수는 적지 않았습니다.",
      "입력에 없는 내용이라 생략하겠습니다.",
      "알겠습니다. 아래와 같이 정리했습니다.",
      "우리 ○○이는 잘했습니다.",
      "{\"comment\": \"...\"}",
      "이 문장은 쓰지 않겠습니다.",
    ]) expect(hasMentLeak(s), s).toBe(true);
  });
  it("🔴 수업 사실은 걸리지 않는다(오탐 금지)", () => {
    for (const s of [
      "오늘은 일일 테스트를 보지 않았습니다.",
      "오답을 다시 써 보며 정리했습니다.",
      "오답 노트를 작성했습니다.",
      "영어 문장을 빼먹지 않고 끝까지 썼습니다.",
      "숙제를 하나도 빠뜨리지 않았습니다.",
      "영어 글을 쓰는 연습을 했습니다.",
      "수업 규칙을 잘 지켜 주었어요.",
      "규칙을 찾아 대응 관계를 식으로 나타냈습니다.",
      "조건에 맞는 수를 차례로 찾았습니다.",
      "AI 수학 특강에도 열심히 참여했습니다.",
      "※ 다음 주 수요일은 휴강입니다.",
      "요청하신 대로 보강은 월요일 4시로 잡았습니다.",
      "필기 내용을 적지 않고 답만 썼습니다.",
      "다음 시간엔 계산기를 쓰지 않도록 하겠습니다.",
      "주어진 자료를 표로 정리했습니다.",
      "오늘 수업 내내 한국말을 쓰지 않았습니다.",
      "영어 수업에서 우리말을 사용하지 않겠다고 스스로 약속했습니다.",
      "다음 시간에 한 번 더 짚어 확실히 챙기겠습니다.",
      "우리 재윤이가 공배수와 최소공배수를 차례로 익혔습니다.",
    ]) expect(hasMentLeak(s), s).toBe(false);
  });
  it("줄·문단 구조는 지키고, 선생님이 직접 적은 말이 든 문장은 남긴다", () => {
    expect(stripMentLeaks("첫 문단입니다.\n\n지침에 따라 썼습니다. 둘째 문단입니다.").text).toBe("첫 문단입니다.\n\n둘째 문단입니다.");
    // 선생님 메모에 걸린 말이 그대로 있으면 지운다고 보지 않는다(메모를 AI가 바꿔 써도 걸린 글자만 보면 된다).
    expect(stripMentLeaks("지침에 따라 오늘은 쉬었습니다.", ["학교 지침에 따라 휴강"]).text).toBe("지침에 따라 오늘은 쉬었습니다.");
    // 뺄 문장이 없는 줄은 글자 하나 안 바꾼다(표의 전각 공백·겹친 띄어쓰기).
    const table = ["구분　　　　　하　　중하", "수업　태도　　○　　●  잘했습니다.  좋습니다."].join("\n");
    expect(stripMentLeaks(table).text).toBe(table);
  });
});
