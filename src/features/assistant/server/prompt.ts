const WEEKDAY = ["일", "월", "화", "수", "목", "금", "토"];

/**
 * 질문 메시지 — 오늘(한국 시간)과 묻는 사람의 역할을 붙인다(시스템 프롬프트는 캐시라 바뀌는 값은 여기에).
 * `asker` = 화면 표시 역할 이름(원장 · 관리자 …) — 운영 계정은 지점 화면과 같은 '관리자'(ask.ts · displayRoleFor). 이름은 넣지 않는다.
 * 2026-11-11 멘트 시험 — 관리자가 물어도 '원장님'으로 불렀다(시스템 프롬프트가 원장 전용으로 정의 · 질문에 역할이 없었다).
 */
export function questionMessage(question: string, now: Date = new Date(), asker?: string): string {
  const kst = new Date(now.getTime() + 9 * 3_600_000);
  const ymd = kst.toISOString().slice(0, 10);
  const hm = kst.toISOString().slice(11, 16);
  const who = asker?.trim() ? ` · 묻는 사람: ${asker.trim()}` : "";
  return `오늘은 ${ymd}(${WEEKDAY[kst.getUTCDay()]}) · 지금 ${hm}(한국 시간)${who}\n\n질문: ${question}`;
}

/** `scopeKeys` = 그 차례 답이 쓴 자료의 묶음 키(s2_0096 · null = 표지 전 옛 답) — 이어 묻기 답의 저장 표지에 합친다(앞 답의 숫자를 다시 말할 수 있다). */
export type PastTurn = { question: string; report: AssistantReport | null; queries: Pick<QueryResult, "id" | "purpose" | "sql">[]; scopeKeys?: readonly string[] | null };

/**
 * 지난 대화 한 차례를 다음 질문이 이어 쓸 수 있는 짧은 글로(도구 기록 전체를 다시 보내지 않는다).
 * 🔴 지난 차례의 조회 번호(q1…)는 넣지 않는다 — 새 차례도 q1부터 세므로 AI가 옛 번호를 가리키면 이번 조회에 묶인다(적대 리뷰 2026-11-06).
 *    지난 결과가 필요하면 아래 SQL로 다시 조회한다.
 */
export function pastAnswerText(turn: PastTurn): string {
  const lines: string[] = [];
  const r = turn.report;
  if (r) {
    lines.push(`[보고서] ${r.title}`);
    for (const b of r.blocks) {
      // 강조 표시는 벗긴다(화면 서식일 뿐 — 맥락 글자만 넘긴다 · rich-text.ts).
      if (b.type === "summary") lines.push(plainRich(b.text));
      else if (b.type === "kpi") lines.push(b.items.map((i) => `${i.label} ${i.value}${i.unit ?? ""}`).join(" · "));
      else if (b.type === "callout") lines.push(`${plainRich(b.title)}: ${plainRich(b.text)}`);
      else if (b.type === "list") lines.push(...b.items.map((i) => `- ${plainRich(i)}`));
      else if (b.type === "advice") lines.push(...b.items.map((i) => `[비서 의견] ${plainRich(i.action)} — ${plainRich(i.why)}`));
      else lines.push(`(${b.type === "chart" ? "차트" : "표"} ${b.title})`);
    }
  } else {
    lines.push("(답을 내지 못했습니다)");
  }
  if (turn.queries.length) lines.push("(지난 조회 — 이번 차례의 조회 번호로 쓸 수 없다. 필요하면 다시 조회한다)");
  for (const q of turn.queries) lines.push(`- ${q.purpose}: ${clipText(q.sql.replace(/\s+/g, " "), 600)}`);
  return clipText(lines.join("\n"), 4000, "…");
}
