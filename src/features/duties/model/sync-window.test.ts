import { describe, expect, it } from "vitest";
import { syncDays } from "./sync-window";

describe("syncDays — 다시 맞출 날", () => {
  it("오늘과 최근 7일만 남긴다(옛 날 · 앞날은 버린다) · 겹침 없이 날짜순", () => {
    expect(syncDays(["2026-11-10", "2026-11-03", "2026-11-02", "2026-08-01", "2026-11-11", "2026-11-10"], "2026-11-10")).toEqual(["2026-11-03", "2026-11-10"]);
  });
  it("덧붙인 날(오늘 · 열린 지난 날)도 같은 창을 지난다", () => {
    expect(syncDays([], "2026-11-10", ["2026-11-10", "2026-11-09", "2026-10-01"])).toEqual(["2026-11-09", "2026-11-10"]);
  });
});
