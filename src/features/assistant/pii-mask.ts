/**
 * 학원 비서 조회 결과의 주민번호 가림 — 앞 6자리(생년월일) + 뒷자리 첫 자리만 남긴다(원장 2026-11-11
 * *"주민번호 앞자리 6개 및 뒷자리 1개만 보내. 나머진 됐고"*).
 * 1차 = DB 보기(s2_0067 — 이력서 residentId · 발행 명세서 residentRegNo · 두 칸의 `######-#######` 꼴).
 * 2차 = 여기 — 조회 결과가 AI로 가기 전 모든 글자 칸(executor `cell`). 줄표 없이 · 띄어 · 긴 줄표 · 전각으로 적어 1차를 지난 것까지.
 * 생년월일로 읽히는 앞 6자리(월 01~12 · 일 01~31) + 성별 자리(1~8) + 6자리일 때만 — 숫자가 앞뒤로 이어지면(계좌·소수·해시 속) 건드리지 않는다.
 * 순수 함수(서버·화면 공용).
 */
const DIGIT = "[0-9０-９]";
/** 사이 공백(줄바꿈·NBSP·폭 없는 공백 포함)과 구분자(줄표 여러 꼴 · 마이너스 · 점 · 가운뎃점 · 빗금) — 재리뷰 2026-11-11. */
const GAP = "[\\s\\u00A0\\u200B-\\u200D]*";
const SEP = `${GAP}(?:[-–—－‐‑−.·/]${GAP})?`;
const RRN = new RegExp(
  `(?<![0-9０-９.])(${DIGIT}{2}(?:[0０][1-9１-９]|[1１][0-2０-２])(?:[0０][1-9１-９]|[12１２]${DIGIT}|[3３][01０１]))` +
    `${SEP}([1-8１-８])${DIGIT}{6}(?![0-9０-９])`,
  "g",
);

export function maskResidentNo(text: string): string {
  return text.replace(RRN, (_m, front: string, g: string) => `${front}-${g}******`);
}
