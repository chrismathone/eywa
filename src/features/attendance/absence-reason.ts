/**
 * 비교용 정규화 — **공백 제거 + 소문자화**(학생 검색 `normalizeSearchText`와 같은 규약).
 * 실데이터가 `가족 여행`·`가족여행`·`가족 휴가`·`가족휴가`처럼 띄어쓰기만 다른 같은 말을 섞어 쓴다.
 */
function normalize(note: string): string {
  return note.replace(/\s+/g, "").toLowerCase();
}

