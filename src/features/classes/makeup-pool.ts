/**
 * **보이지 않는 '보강' 반** — 반 없는 보강 출결이 앉는 자리(0241a). 순수 판정·이름 짓기만(Vitest).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ## 한 줄 요약
 * 강사마다 **눈에 안 보이는 반**이 하나씩 있고, "어느 반에서 한 건지 알 수 없는 보강"의 출결이 거기 앉는다.
 * 그래서 시수가 그 강사 몫으로 잡히고, 칸도 평소처럼 고칠 수 있다.
 *
 * ## 왜 이렇게 하나 (다음 사람이 되돌리기 전에 꼭 읽을 것)
 * 원장 2026-09-02, 순서대로:
 *   ① *"보강건으로 보고서 발송한 학생들에 대해서 출석부에 입력되지 않는 문제 해결"*
 *   ② *"이런 보강 보고서 반에서 한 기록은 필요 없고 그냥 출석부에 '보강' 반을 임시로 만들어서
 *      그 아래에 학생이 있으면 돼. 그날만 출석한것처럼"*
 *   ③ *"어느 반에서 보강한건 모르지 당연히 저렇게 보강하면 · 반 보강이 아니니까"*
 *   ④ *"보고서 발송건에 대해서는 자동 입력 되어야지 / 발송 날자에 대해서는 수정할수도 있어야하고"*
 *   ⑤ *"실제로 수업을 했는데 출석부에 시수가 없으면 이상하지."*
 *   ⑥ *"어디에서도 확인할 수 없는 그냥 코드로만 존재하는 가짜반을 만들자."*
 *
 * ③ 때문에 **강사에게 반을 물을 수 없고**(그런 시도를 한 번 했다가 원복했다 — 물으면 아무 반이나 골라
 * 그 반 시수가 는다), ⑤ 때문에 **진짜 출결 행이어야 하며**(화면 표시만으로는 시수가 안 잡힌다),
 * ④ 때문에 **고칠 수 있어야 한다**. 셋을 동시에 만족하는 자리가 이 반이다.
 *
 * 🔴 **`attendance_records.class_id`를 비우는 길은 채택하지 않았다.** 출결의 **강사 귀속은 반에서**
 *    나온다(담임·교시 담당). 입력자(`recorded_by`)는 귀속이 아니다 — 실측 영어 출결 1,146행 중
 *    1,138행이 한 사람이 대신 찍은 것이다. 반을 비우면 그 행은 **주인이 없어** 시수가 아무에게도 안 간다.
 *
 * ## 안 보이게 하는 장치 둘 (순서가 중요하다)
 * ① **`is_active = false`** — 활성만 보는 거의 모든 목록(수업목록 기본·반 드롭다운·시간표·원스크린
 *    로스터·ECS/MCS 랜딩·통계)에서 **필터 한 줄 없이** 자동으로 빠진다. 이게 주 방어다.
 * ② **`is_makeup_pool` 컬럼** — 그래도 비활성까지 보여주는 화면(수업목록 상태 필터)에서만 한 번 더 뺀다.
 * 🔴 **이름으로 판정하지 말 것.** 이름을 바꾸면 배선이 **에러 없이 조용히** 끊긴다(테스트 학생 '학원이'
 *    건에서 실제로 겪었다). 아래 `makeupPoolName`은 **표시용**이고 판정 근거가 아니다.
 *
 * ## 이 반이 하면 안 되는 것
 * 🔴 **교시(`class_schedules`)를 만들지 말 것** — 있으면 출석부 반 목록·'미입력 반' 신호에 매일 걸려
 *    사무실 화면에 가짜 경고가 쌓인다(학원이 전용 반에서 못박은 것과 같은 이유).
 * 🔴 **수강(`enrollments`)을 만들지 말 것** — 보강은 등록이 아니다. 명단·청구·회차가 전부 흔들린다.
 *    출결 행만 있으면 출석부는 그 학생을 그린다(보강 칸은 원래 수강 없이 쓴다 — `writeEligibility`, attendance/write-eligibility.ts).
 * 🔴 **사람이 고르는 선택지에 넣지 말 것**(반 드롭다운·이동·배정) — 고를 수 있게 되는 순간
 *    "보강 반에 등록된 학생"이 생기고 그 뒤는 되돌리기 어렵다.
 */

/** 표시 이름의 앞머리 — **판정 근거가 아니다**(판정은 `is_makeup_pool`). */
export const MAKEUP_POOL_PREFIX = "보강";

/**
 * 그 강사의 보강 반 이름. 이름이 겹치면 사람이 헷갈리므로 강사명을 붙인다.
 * ⚠️ 강사명이 비면 접미사 없이 `보강` — 이름은 표시용이라 비어도 배선이 안 끊긴다(그게 이 설계의 요점).
 */
export function makeupPoolName(teacherName: string | null | undefined): string {
  const n = (teacherName ?? "").trim();
  return n ? `${MAKEUP_POOL_PREFIX} · ${n}` : MAKEUP_POOL_PREFIX;
}

/**
 * 이 반이 보이지 않는 보강 반인가 — **컬럼 하나만** 본다.
 * ⚠️ 컬럼이 아직 없는 스키마(0241a 미적용)에서는 `undefined`가 와서 항상 false다 = 종전과 같다.
 */
export function isMakeupPoolClass(row: { is_makeup_pool?: boolean | null } | null | undefined): boolean {
  return row?.is_makeup_pool === true;
}

export type MakeupOwnerPick = { id: string; via: "created_by" | "teacher_name" | "saver" };

/**
 * 보강 보고서 한 건이 **누구의 보강 반**에 앉는가 — 저장한 사람이 아니라 **보고서의 소유자**다.
 *
 * 사무실이 강사 대신 저장하면 저장자(`user`)로 귀속했을 때 보강 반이 사무실 계정 앞으로 생기고, 그 강사
 * 출석부엔 안 뜬다(2026-09-02 점검 — 실측 그런 건은 0건이라 **예방**이다). 규칙은 셋이고 순서가 있다:
 *   ① `created_by` — 0172a가 정한 **소유 계정**("누구 원스크린에 뜨는가"). 갱신 때도 DB 트리거가
 *      원 작성자를 보존하므로 남이 고쳐 저장해도 안 바뀐다. 있으면 이것이 답이다.
 *   ② `teacher_name` — 표시용 이름이라 저장자가 덮어쓰는 값(보존 트리거 없음). ①이 비었을 때만,
 *      같은 학원의 **활성 직원(학생 계정 제외)** 중 표시 이름이 **정확히 하나** 일치할 때만 쓴다.
 *      🔴 동명이인·미등록(옛 별명 '수진'·'희영1')이면 **귀속하지 않는다** — 이름으로 남의 계정에 붙이는
 *      것보다 안 만드는 게 낫다([[#93]]과 같은 결. 나중에 스크립트로 채울 수 있다).
 *   ③ 저장자 — 소유자 정보가 **아예 없을 때만**(①·② 둘 다 빈 값). 스크립트엔 저장자가 없어 null.
 * ⚠️ 소급 스크립트(`scripts/_oneoff/backfill-makeup-attendance.mjs`)가 같은 규칙의 CJS/ESM 사본을 든다 —
 *    여기를 바꾸면 그쪽도 함께.
 */
export function pickMakeupOwner(input: {
  createdBy: string | null | undefined;
  teacherName: string | null | undefined;
  /** `teacherName`과 표시 이름이 **정확히** 같은 활성 직원(학생 계정 제외) — 호출부가 조회해 넘긴다. */
  sameName: readonly { id: string }[];
  /** 저장한 계정 — 소유자 정보가 아예 없을 때만 쓴다. */
  saver: string | null | undefined;
}): MakeupOwnerPick | null {
  if (input.createdBy) return { id: input.createdBy, via: "created_by" };
  const name = input.teacherName ?? "";
  if (name.trim()) {
    return input.sameName.length === 1 ? { id: input.sameName[0]!.id, via: "teacher_name" } : null;
  }
  return input.saver ? { id: input.saver, via: "saver" } : null;
}
