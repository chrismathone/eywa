/** 문자열 → 안정적인 작은 해시(결정적). 같은 학생·같은 날은 늘 같은 변형이라 재생성해도 결이 흔들리지 않는다. */
export function styleSeedIndex(seed: string, buckets: number): number {
  let h = 0;
  for (let i = 0; i < seed.length; i++) h = (h * 31 + seed.charCodeAt(i)) % 2147483647;
  return buckets > 0 ? h % buckets : 0;
}

/** 이 학생·이 날짜에 적용할 문체 변형 블록. seed가 비면 변형을 걸지 않는다(기존 동작). */
export function commentStyleDirective(seed: string): string {
  if (!seed.trim()) return "";
  const pick = COMMENT_STYLE_VARIANTS[styleSeedIndex(seed, COMMENT_STYLE_VARIANTS.length)]!;
  return ["[이번 알림장의 결]", `- ${pick}`, "- 사실을 더하거나 빼지 말고 **순서와 초점만** 바꾸세요."].join("\n");
}

/** {{key}} → vars[key]. 없는 키는 빈 문자열. edutrix interpolatePrompt 대응. */
export function interpolate(template: string, vars: Record<string, string>): string {
  return template.replace(/\{\{\s*(\w+)\s*\}\}/g, (_, k: string) => (k in vars ? vars[k]! : ""));
}

