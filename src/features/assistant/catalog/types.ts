/**
 * 학원 비서 DB 지도 — 표마다 AI에게 줄 한국어 설명. 보기(`assistant.<표>`)를 만드는 규칙은 SQL 쪽(지점 칸 · 비밀 칸 패턴)이 정하고,
 * 여기는 "무엇을 담고 어떻게 읽나"만 적는다. 표 목록 + `ko`는 시스템 프롬프트(캐시), `notes`·`columns`는 `describe_table`이 준다.
 */
export type AssistantTableDoc = {
  /** public 표 이름 = assistant 보기 이름. */
  name: string;
  /** 짧은 이름(2~8자) — 진행 단계에 '어떤 자료를 보는 중'으로 뜬다(원장 *"어떤 db를 조회중이고 어떤 프로그레스중인지 단계가 표시"*). */
  label: string;
  /** 한 줄 설명(60자 안팎) — 무엇을 담고 언제 쌓이나. */
  ko: string;
  /**
   * 읽는 법(400자 안팎) — 상태·종류 칸의 값과 뜻, 소프트 삭제 칸, 금액 단위, 자주 묻는 질문에 쓸 칸,
   * 헷갈리기 쉬운 비슷한 표와의 차이. 없으면 생략.
   */
  notes?: string;
  /** 칸별 짧은 뜻 — 이름만으로 뜻이 분명하지 않은 칸만. */
  columns?: Record<string, string>;
  /** 학원 운영 질문에 거의 쓰이지 않는 내부 표(대기열·잠금·동기화 기록 등) — 목록 맨 뒤로 보내고 설명을 짧게. */
  internal?: true;
};
