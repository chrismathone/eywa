-- 0193a — 수강료 단가표: attendance 이관 산물 54건을 목록에서 내린다(비활성화).
--
-- 원장 2026-08-07: *"교재 및 기타에 왜 고등 통합과학 attendance 단가표 이관 이런게 뜨지?"* →
-- *"attendance 단가표 이관 이런건 전부 제거하고 중복(기존에 이미 존재했던)이면 제거하고 병합시켜버려"*.
--
-- 실측(적용 직전): `note = 'attendance 단가표 이관(2026-07-13)'` **54건 / 전체 104건**.
-- 2026-07-13 D:\attendance 이식 때 들어온 옛 단가표가 정식 단가표 옆에 그대로 남아 있었다.
--
-- 🔴 **지우지 않고 비활성화한다.** 모든 picker(계산기 과목·교재/기타·할인, 수납 회차 확정 단가 후보)가
--    `is_active`로 거르므로 **화면에서는 삭제와 똑같이 사라진다.** 그런데 되돌릴 수 있고, 이 54건 중
--    일부는 정식 목록에 대응이 **없다**(아래 과학 4건). 되돌릴 수 없는 삭제를 먼저 할 이유가 없다.
--    완전 삭제가 필요하면 같은 조건으로 delete하면 된다(이 표를 참조하는 FK는 없다 — 실측 0개, 견적은
--    이름·금액을 스냅샷으로 복사해 저장하므로 **이미 저장된 견적·청구서는 영향받지 않는다**).
--
-- ⚠️ **"중복이면 제거"는 자동으로 판정할 수 없었다**: 이름이 그대로 겹치는 짝은 **0건**이고
--    (`중등국어(재)` vs `중등국어 (재원생)`처럼 표기가 다르다), 금액 일치는 신호가 못 된다
--    (24,000원 하나에 8개 항목이 걸린다 — 금액으로 묶으면 엉뚱한 것을 지운다).
--    그래서 **"이관 산물이면 내린다"** 한 가지 기준만 쓴다. 정식 항목은 하나도 안 건드린다.
--
-- ⚠️ 그중 **과학 4건**(기타/고등 통합과학·과학특강1·과학특강2·중등 과학정규)은 정식 분류에 대응이
--    **없다** — 단가표 분류에 '과학'이 아예 없어서 이관 때 '기타'로 들어온 것들이다. 과학 수업 견적을
--    쓰신다면 이 넷은 되살려 제 분류로 옮겨야 한다(분류 추가가 선행). 그때까지는 함께 내려 둔다.
--
-- ⚠️ 멱등: 이미 내려간 행은 그대로. 되돌리기 = 같은 where로 `is_active = true`.

update public.tuition_catalog
   set is_active = false, updated_at = now()
 where note = 'attendance 단가표 이관(2026-07-13)'
   and is_active;

