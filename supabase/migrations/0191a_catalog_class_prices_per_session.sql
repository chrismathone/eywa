-- 0191a — 수강료 단가표: 아직 종류가 없는 **수업 단가**를 전부 '회당 단가'로 확정.
--
-- 원장 2026-08-07: *"미지정 싹다 회당"*. 0190a에서 확실한 것(EiE 월정액 12건·할인 3건)만 채우고 남겨 둔
-- 31건을 원장이 확인해 준 것이다.
--
-- 대상(적용 직전 실측 = 미지정 35건 중 31건):
--   · 수학 18건 (21,250~43,750)   예: '중등M 정규반 (3T2H)' · '고등M_메디컬반 (2T3H)'
--   · 영어 11건 (24,000~40,875)   예: '중등E_정규 (3T2H)' · '고등E_정규 (2T3H)'
--   · 국어  2건 (25,000·31,250)   '중등국어 (재원생/비재원생)'
--   전부 반 이름에 시수 표기((3T2H) 등)가 붙은 **수업**이고 금액대가 회당 단가 범위다.
--
-- 🔴 **'기타' 4건은 제외한다** — 레벨 테스트 비용 · 셔틀버스비 · 스터디케어 · 시스템 사용료.
--    수업이 아니라 부대비용이라 "회당"이 성립하지 않고, 회당으로 표시하면 수납 '회차 확정'의 단가
--    후보 목록에 셔틀버스비가 뜬다. 계산기에서는 '교재 및 기타'로 들어가 단가 종류를 아예 안 쓰므로
--    미지정으로 두어도 동작에 문제가 없다. 정할 값이 생기면 단가표 목록에서 한 번 클릭으로 바꾼다.
--
-- ⚠️ 멱등: 비어 있는 행만 건드린다(이미 고른 값을 덮지 않는다). 스키마 변경 없음.

update public.tuition_catalog
   set pricing_mode = 'per_session', updated_at = now()
 where pricing_mode is null
   and category in ('수학', '영어', '국어');

